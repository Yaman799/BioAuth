def translate_string(lang: str, key: str, **kwargs: Any) -> str:
    lang_code = str(lang or "en").strip().lower()
    if lang_code not in STRINGS:
        lang_code = "en"
    text = STRINGS.get(lang_code, {}).get(key) or STRINGS["en"].get(key) or key
    try:
        return text.format(**kwargs)
    except Exception:
        return text


def translate_backend_result(lang: str, result: Optional[Dict[str, Any]], default_key: str = "", default_message: str = "", **default_kwargs: Any) -> str:
    payload = result if isinstance(result, dict) else {}
    message_key = str(payload.get("message_key") or default_key or "").strip()
    message_params = dict(payload.get("message_params") or {}) if isinstance(payload.get("message_params"), dict) else {}
    if default_kwargs:
        for name, value in default_kwargs.items():
            message_params.setdefault(name, value)
    if message_key:
        return translate_string(lang, message_key, **message_params)
    raw_message = str(payload.get("message") or default_message or "")
    if raw_message:
        return raw_message
    if default_key:
        return translate_string(lang, default_key, **default_kwargs)
    return ""


